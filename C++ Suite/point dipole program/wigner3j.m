function[threej]=wigner3j(l1,l2,l3,m1,m2,m3)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%         Determine the values for the Wigner 3j symbols.         %%%%%
%%%%%                                                                 %%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%              Last Modified:    Jan 29 2022                      %%%%%
%%%%%                                                                 %%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
threej=0;
em1((2*l1+1),1)=zeros;
em2((2*l2+1),1)=zeros;
em3((2*l3+1),1)=zeros;
for i=1:(2*l1+1)
    em1(i,1)=-l1+i-1;
end
for i=1:(2*l2+1)
    em2(i,1)=-l2+i-1;
end
for i=1:(2*l3+1)
    em3(i,1)=-l3+i-1;
end
if ((m1+m2+m3==0))
    if((abs(l1-l2)<l3)||(abs(l1-l2)==l3))
        if(l3<(l1+l2)||l3==(l1+l2))
            if(rem((l1+l2+l3),1)==0) 
                if(ismember(m1,em1))
                    if(ismember(m2,em2))
                        if(ismember(m3,em3))
sign=(-1)^(l1-l2-m3);
tri=sqrt(tricoeff(l1,l2,l3));
root=sqrt(factorial(l1+m1)*factorial(l1-m1)*factorial(l2+m2)*factorial(l2-m2)*factorial(l3+m3)*factorial(l3-m3));
ex=x(l1,l2,l3,m1,m2,m3);
threej=sign*tri*root*ex;
                end
            end
        end
    end
        end
    end
end
