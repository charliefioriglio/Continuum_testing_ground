function [y] = x(l1,l2,l3,m1,m2,~)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%              Last Modified:    Jan 29 2022                      %%%%%
%%%%%                                                                 %%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
t(5,1)=zeros;
t(1,1)=-(l3-l2+m1);
t(2,1)=-(l3-l1-m2);
t(3,1)=(l1+l2-l3);
t(4,1)=(l1-m1);
t(5,1)=(l2+m2);

tmax=min(t(3:5,1));
tmin=max(t(1:2,1));
if(tmin<0)
    tmin=0;
end

y=0;
if (tmin<tmax||tmin==tmax)
for t=tmin:tmax
    y=y+((-1)^t)/(factorial(t)*factorial(l3-l2+t+m1)*factorial(l3-l1+t-m2)*factorial(l1+l2-l3-t)*factorial(l1-t-m1)*factorial(l2-t+m2));
end
end

